def get_day_index(first_date: date, today: date) -> int:
    """
    初回記録日からの経過日数を計算（1始まり）
    
    Args:
        first_date: 初回記録日
        today: 今日の日付
    
    Returns:
        day_index: 1始まりの日数（初回記録日=1）
    """
    return (today - first_date).days + 1


def get_daily_cta_copy(day_index: int) -> str | None:
    """
    日数に応じたCTAコピーを取得
    
    Args:
        day_index: 経過日数（1始まり）
    
    Returns:
        コピー文字列（1〜30）、それ以外はNone
    """
    if 1 <= day_index <= 30:
        return DAY_COPY.get(day_index)
    return None
